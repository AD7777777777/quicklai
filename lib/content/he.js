// Prepends an RLM (Right-to-Left Mark, U+200F) so external renderers that
// don't know this is Hebrew content — WhatsApp/Facebook/Slack link-preview
// cards, which render the raw og:title/og:description string completely
// outside our page's dir="rtl" context — correctly detect right-to-left
// paragraph direction from the very first character. Without this, since
// our text often starts with an LRM-wrapped Latin term like "Quicklai" or
// "AI" (itself a strong-LTR-typed character), bidi auto-detection can
// misjudge the whole paragraph as left-to-right and visibly scramble
// sentence order — even though the same text renders correctly on the
// actual site, where <html dir="rtl"> overrides auto-detection entirely.
// Use this ONLY for metadata (title/description/openGraph/twitter) fields,
// never for on-page visible content, which doesn't need it.
export function rtlMeta(str) {
  return "\u200F" + str;
}
